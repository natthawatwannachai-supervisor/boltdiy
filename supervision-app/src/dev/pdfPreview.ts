async function render() {
  const status = document.getElementById('status');
  const frame = document.getElementById('frame') as HTMLIFrameElement | null;

  if (status) {
    status.textContent = 'กำลังสร้าง...';
  }

  const { doc } = await buildMonthlyReport({ profile, records, monthKey: '2025-06' });
  const url = doc.output('bloburl');

  if (frame) {
    frame.src = String(url);
  }

  if (status) {
    status.textContent = `สร้างสำเร็จ • ${doc.getNumberOfPages()} หน้า`;
  }

  // Exposed so an automated check can assert on the generated bytes.
  (window as unknown as { __pdf?: string }).__pdf = doc.output('datauristring');
}

