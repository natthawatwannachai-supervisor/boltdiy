/** A scribbled signature, drawn on a transparent canvas. */
function signatureDataUrl(): string {
  const canvas = document.createElement('canvas');

  canvas.width = 420;
  canvas.height = 140;

  const context = canvas.getContext('2d');

  if (context) {
    context.strokeStyle = '#111827';
    context.lineWidth = 4;
    context.lineCap = 'round';
    context.beginPath();
    context.moveTo(30, 100);
    context.bezierCurveTo(90, 10, 130, 130, 190, 60);
    context.bezierCurveTo(240, 10, 250, 120, 320, 70);
    context.lineTo(390, 90);
    context.stroke();
  }

  return canvas.toDataURL('image/png');
}

/** A placeholder photo so the appendix has something to lay out. */
function photo(label: string, seed: number): SupervisionRecord['images'][number] {
  const canvas = document.createElement('canvas');

  canvas.width = 960;
  canvas.height = 640;

  const context = canvas.getContext('2d');

  if (context) {
    const gradient = context.createLinearGradient(0, 0, 960, 640);

    gradient.addColorStop(0, ['#34D399', '#5EEAD4', '#A7F3D0'][seed % 3]);
    gradient.addColorStop(1, ['#0F766E', '#047857', '#0D9488'][seed % 3]);
    context.fillStyle = gradient;
    context.fillRect(0, 0, 960, 640);
    context.fillStyle = '#ffffff';
    context.font = 'bold 56px Kanit, sans-serif';
    context.textAlign = 'center';
    context.fillText(label, 480, 340);
  }

  return { url: canvas.toDataURL('image/jpeg', 0.8), path: `demo/${seed}`, name: label, size: 250 * 1024 };
}
